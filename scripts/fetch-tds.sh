#!/bin/bash
#
# fetch-tds.sh — populate engine-artifacts/texmf/ with a minimal TeX Live
# Distribution tree, sufficient for compiling \documentclass{article} docs
# with pdflatex.
#
# Pulls files from Ubuntu's `texlive-latex-base` + `texlive-latex-recommended`
# packages via a one-shot Docker container, plus the pre-built `.fmt` files.
#
# Idempotent: skips if engine-artifacts/texmf already has content.
#
# Usage:
#   bash scripts/fetch-tds.sh

set -eu

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TARGET="$REPO_ROOT/engine-artifacts/texmf"

TDS_SNAPSHOT="${TDS_SNAPSHOT:-locked}"
TDS_BUILD_ID="$TDS_SNAPSHOT"
if [ "$TDS_SNAPSHOT" = locked ]; then TDS_BUILD_ID="locked:$(sha256sum "$REPO_ROOT/scripts/data/tds-packages.lock" | cut -d " " -f1)"; fi
if [[ "$TDS_SNAPSHOT" != locked && ! "$TDS_SNAPSHOT" =~ ^[0-9]{8}T[0-9]{6}Z$ ]]; then
  echo "Invalid TDS_SNAPSHOT: expected YYYYMMDDTHHMMSSZ" >&2
  exit 1
fi
if [ -f "$TARGET/.tds-complete" ]; then
  if [ "$(cat "$TARGET/.tds-complete")" != "$TDS_BUILD_ID" ]; then
    echo "TDS snapshot changed; move the existing tree aside before fetching." >&2
    exit 1
  fi
  for required in tex/latex/base/article.cls tex/latex/base/latex.ltx web2c/texmf.cnf ls-R; do
    if [ ! -s "$TARGET/$required" ]; then echo "Incomplete TDS: $required missing" >&2; exit 1; fi
  done
  echo "Verified complete TDS at $TARGET ($TDS_SNAPSHOT)"
  exit 0
fi
if [ -d "$TARGET" ] && [ -n "$(ls -A "$TARGET")" ]; then
  echo "TDS has no completion marker; move the partial/legacy tree aside before fetching." >&2
  exit 1
fi
FINAL_TARGET="$TARGET"
mkdir -p "$REPO_ROOT/engine-artifacts"
TARGET=$(mktemp -d "$REPO_ROOT/engine-artifacts/texmf-staging.XXXXXX")
TDS_STAGING_NAME=$(basename "$TARGET")
trap 'rm -rf "$TARGET"' EXIT

echo "Fetching TDS with pinned Ubuntu packages ($TDS_SNAPSHOT)..."

# NOTE: the container script below is ONE single-quoted string. An apostrophe
# anywhere inside it (even in a comment) silently truncates the container
# script and hands the rest to the HOST shell — which is exactly how a
# "missing biblatex.sty" wild-goose chase happened. No apostrophes!
docker run --rm -e TDS_SNAPSHOT="$TDS_SNAPSHOT" -e TDS_STAGING_NAME="$TDS_STAGING_NAME" -v "$REPO_ROOT:/workspace" ubuntu:24.04@sha256:2198e4c65076e9cb0b3d695219df667c0e3b0072da64ca3c2648aca17dcecaf5 bash -c '
set -e
export DEBIAN_FRONTEND=noninteractive
# The minimal image has no HTTPS certificate bundle. Bootstrap trust before
# asking apt to contact the HTTPS snapshot endpoint.
apt-get update -qq -o APT::Update::Error-Mode=any > /dev/null
apt-get install -qq -y --no-install-recommends ca-certificates > /dev/null
if [ "$TDS_SNAPSHOT" != locked ]; then
  apt --snapshot "$TDS_SNAPSHOT" update -qq -o APT::Update::Error-Mode=any > /dev/null
fi
# Every package contributing TeX files is version-pinned; apt verifies the
# package digests against signed Ubuntu indexes.
mapfile -t packages < /workspace/scripts/data/tds-packages.lock
if [ "$TDS_SNAPSHOT" = locked ]; then
  apt-get install -qq -y --no-install-recommends "${packages[@]}" > /dev/null
else
  apt --snapshot "$TDS_SNAPSHOT" install -qq -y --no-install-recommends "${packages[@]}" > /dev/null
fi
dpkg-query -W -f="\${Package}=\${Version}\n" | grep -E "^(texlive|tex-common|fonts-|lmodern|tex-gyre|preview-latex-style|tipa)" > /workspace/engine-artifacts/tds-packages-installed.txt
cmp /workspace/scripts/data/tds-packages.lock /workspace/engine-artifacts/tds-packages-installed.txt
echo "[+] copying /usr/share/texlive/texmf-dist tree..."
cp -r /usr/share/texlive/texmf-dist/. /workspace/engine-artifacts/$TDS_STAGING_NAME/
echo "[+] merging /usr/share/texmf tree (lmodern + system fonts)..."
if [ -d /usr/share/texmf ]; then
  cp -rn /usr/share/texmf/. /workspace/engine-artifacts/$TDS_STAGING_NAME/ 2>/dev/null || true
fi
echo "[+] staging pre-built .fmt files..."
mkdir -p /workspace/engine-artifacts/$TDS_STAGING_NAME/web2c/pdftex
cp /var/lib/texmf/web2c/pdftex/pdflatex.fmt /workspace/engine-artifacts/$TDS_STAGING_NAME/web2c/pdftex/ 2>/dev/null || true
cp /var/lib/texmf/web2c/pdftex/latex.fmt    /workspace/engine-artifacts/$TDS_STAGING_NAME/web2c/pdftex/ 2>/dev/null || true
echo "[+] staging updmap-generated font maps..."
# pdftex.map / psfonts.map etc. are GENERATED by updmap into /var/lib/texmf,
# not shipped in texmf-dist. Without pdftex.map, pdfTeX ships all pages and
# then dies at PDF finalization ("cannot open font map file" → no fonts to
# embed → "Fatal error occurred, no output PDF file produced").
# -L dereferences: the canonical names (pdftex.map → pdftex_dl14.map) are
# symlinks on Ubuntu, and the symlink cleanup below deletes ALL symlinks.
mkdir -p /workspace/engine-artifacts/$TDS_STAGING_NAME/fonts/map
if [ -d /var/lib/texmf/fonts/map ]; then
  cp -rnL /var/lib/texmf/fonts/map/. /workspace/engine-artifacts/$TDS_STAGING_NAME/fonts/map/ 2>/dev/null || true
fi
MAPS=/workspace/engine-artifacts/$TDS_STAGING_NAME/fonts/map
if [ ! -f "$MAPS/pdftex/updmap/pdftex.map" ] && [ -f "$MAPS/pdftex/updmap/pdftex_dl14.map" ]; then
  cp "$MAPS/pdftex/updmap/pdftex_dl14.map" "$MAPS/pdftex/updmap/pdftex.map"
fi
if [ ! -f "$MAPS/dvips/updmap/psfonts.map" ] && [ -f "$MAPS/dvips/updmap/psfonts_t1.map" ]; then
  cp "$MAPS/dvips/updmap/psfonts_t1.map" "$MAPS/dvips/updmap/psfonts.map"
fi
ls -la "$MAPS/pdftex/updmap/" || true
echo "[+] materializing symlinks (Debian ships some package files as links)..."
# Deleting all symlinks used to eat real files — pdftex.map first, then
# biblatex.sty (texlive-bibtex-extra links it). Resolve each link inside
# the container (where the target tree still exists) and copy the bytes;
# only links without a real file target (dirs, dangling) are dropped.
find /workspace/engine-artifacts/$TDS_STAGING_NAME -type l | while read -r link; do
  target=$(readlink -f "$link" || true)
  if [ -n "$target" ] && [ -f "$target" ]; then
    cp --remove-destination "$target" "$link"
  else
    rm -f "$link"
  fi
done
# Wipe any leftover ls-R that points to the distro path.
rm -f /workspace/engine-artifacts/$TDS_STAGING_NAME/ls-R
echo "[+] trimming assets unusable in the WASM/PDF-only build..."
# Drop ~120 MB raw / ~30 MB brotli of unreachable assets:
#   fonts/source     METAFONT .mf sources, no mktexpk in WASM
#   fonts/afm        legacy dvips Adobe Font Metric
#   tex/context      ConTeXt format, not LaTeX
#   bibtex/bib       sample biblio data shipped inside packages
#   scripts/*        Perl/Java tools requiring fork
#   tex4ht/source/texdoc/texdoctk/metapost/metafont/mft/xdvi  tools we do not ship
# Kept on purpose: scripts/citation-style-language + scripts/citeproc-lua —
# the CSL processor is pure Lua and runs entirely inside lualatex.wasm.
rm -rf /workspace/engine-artifacts/$TDS_STAGING_NAME/doc \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/fonts/source \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/fonts/afm \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/fonts/type1/public/cbfonts \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/fonts/tfm/public/cbfonts \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/cbfonts \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/utfsym \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/worldflags \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/hwemoji \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/twemojis \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/uantwerpendocs \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/nwejm \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/rutitlepage \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/powerdot-tuliplab \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/ghsystem \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/context \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/bibtex/bib \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/scripts/texdoc \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/scripts/l3build \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/scripts/texlive \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/scripts/checkcites \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/scripts/bib2gls \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/scripts/barracuda \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/scripts/webquiz \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/tex4ht \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/source \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/texdoc \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/texdoctk \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/metapost \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/metafont \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/mft \
       /workspace/engine-artifacts/$TDS_STAGING_NAME/xdvi 2>/dev/null || true
# Keep contrib bibliography styles in full TDS and its integrity index.
echo "[+] verifying bibliography payload (biblatex + CSL)..."
echo "[debug] dpkg: $(dpkg-query -W texlive-bibtex-extra 2>&1 || true)"
echo "[debug] src sty: $(ls -la /usr/share/texlive/texmf-dist/tex/latex/biblatex/biblatex.sty 2>&1 || true)"
echo "[debug] staged sty: $(ls -la /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/biblatex/biblatex.sty 2>&1 || true)"
echo "[debug] staged dir: $(ls /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/biblatex/ 2>&1 | head -8 | tr "\n" " " || true)"
echo "[debug] sty anywhere staged: $(find /workspace/engine-artifacts/$TDS_STAGING_NAME -name biblatex.sty 2>/dev/null | head -2 | tr "\n" " " || true)"
echo "[debug] dpkg -L: $(dpkg -L texlive-bibtex-extra 2>/dev/null | grep -m1 "biblatex\.sty" || echo "NOT IN PACKAGE MANIFEST")"
# Fail loudly if the texlive-bibtex-extra payload changes shape — every one
# of these is load-bearing for the latexmk biblatex/CSL support.
for f in \
  tex/latex/biblatex/biblatex.sty \
  bibtex/bst/biblatex/biblatex.bst \
  tex/latex/logreq/logreq.sty \
  tex/latex/citation-style-language/citation-style-language.sty \
  tex/latex/citation-style-language/styles/apa.csl; do
  if [ ! -e "/workspace/engine-artifacts/$TDS_STAGING_NAME/$f" ]; then
    echo "ERROR: expected $f in the TDS tree (texlive-bibtex-extra layout changed?)" >&2
    exit 1
  fi
done
# The Lua processor dir name differs across TL snapshots.
if [ ! -d /workspace/engine-artifacts/$TDS_STAGING_NAME/scripts/citation-style-language ] \
  && [ ! -d /workspace/engine-artifacts/$TDS_STAGING_NAME/scripts/citeproc-lua ]; then
  echo "ERROR: no citeproc-lua scripts directory in the TDS tree" >&2
  exit 1
fi
ls /workspace/engine-artifacts/$TDS_STAGING_NAME/tex/latex/citation-style-language/locales/ 2>/dev/null | head -3 \
  || echo "WARNING: no CSL locales directory — citeproc may fall back to en-US"
echo "[+] patching texmf.cnf TEXMFROOT for wasm layout..."
# Distros set TEXMFROOT to an absolute system path (e.g. /usr/share/texlive)
# that exists on Linux but not inside our WASM virtual FS. Rewrite the root
# so bibtexu / makeindex / xdvipdfmx — which all rely on kpathsea search but
# do not accept -cnf-line= overrides — can find their support files.
if [ -f /workspace/engine-artifacts/$TDS_STAGING_NAME/web2c/texmf.cnf ]; then
  sed -i \
    -e "s|^TEXMFROOT = .*$|TEXMFROOT = /|" \
    -e "s|^TEXMFDIST = .*$|TEXMFDIST = /texmf-dist|" \
    -e "s|^TEXMFMAIN = .*$|TEXMFMAIN = \$TEXMFDIST|" \
    /workspace/engine-artifacts/$TDS_STAGING_NAME/web2c/texmf.cnf
fi
chown -R '"$(id -u):$(id -g)"' /workspace/engine-artifacts/$TDS_STAGING_NAME
echo "[+] done"
du -sh /workspace/engine-artifacts/$TDS_STAGING_NAME
'

echo
echo "[+] generating ls-R (kpathsea filename database)..."
node -e "
const { readdirSync, statSync, writeFileSync } = require('node:fs');
const ROOT = process.argv[1];
const lines = ['% ls-R -- filename database for kpathsea; do not change this line.'];
function walk(rel) {
  const abs = ROOT + (rel ? '/' + rel : '');
  let entries;
  try { entries = readdirSync(abs); } catch { return; }
  const files = []; const dirs = [];
  for (const e of entries) {
    try {
      const st = statSync(abs + '/' + e);
      if (st.isDirectory()) { files.push(e); dirs.push(e); }
      else if (st.isFile()) { files.push(e); }
    } catch {}
  }
  if (files.length) {
    lines.push('');
    lines.push('./' + rel + ':');
    for (const f of files) lines.push(f);
  }
  for (const d of dirs) walk(rel ? rel + '/' + d : d);
}
walk('');
writeFileSync(ROOT + '/ls-R', lines.join('\n') + '\n');
console.log('  ls-R: ' + lines.length + ' entries, ' + Math.round(lines.join('\n').length/1024) + ' KB');
" "$TARGET"

for required in tex/latex/base/article.cls tex/latex/base/latex.ltx web2c/texmf.cnf ls-R; do
  test -s "$TARGET/$required" || { echo "Incomplete TDS: $required missing" >&2; exit 1; }
done
printf '%s\n' "$TDS_BUILD_ID" > "$TARGET/.tds-complete"
# An empty final directory may have existed before the download.
if [ -d "$FINAL_TARGET" ]; then rmdir "$FINAL_TARGET"; fi
mv "$TARGET" "$FINAL_TARGET"
trap - EXIT
TARGET="$FINAL_TARGET"

echo
echo "TDS ready at $TARGET ($(du -sh "$TARGET" | awk '{print $1}'))"
echo
echo "Notes:"
echo "- The bundled .fmt files were built by Ubuntu's pdflatex and are NOT"
echo "  binary-compatible with our wasm pdflatex. Run scripts/build-fmt.mjs"
echo "  to rebuild them with our engine."
